"""Temporary storage of voice notes.

Two backends behind the same three-method interface:

- ``local``: a directory on the server (a Docker volume shared by api and workers).
  Simple, used for development and single-server deployments.
- ``s3``: an Amazon S3 bucket (or any S3-compatible store through ``S3_ENDPOINT_URL``).
  Used on AWS. Credentials come from the standard AWS chain (EC2 instance role in
  production); this module never reads access keys itself.

Audio is short-lived in both cases: the janitor deletes it after AUDIO_RETENTION_DAYS,
and on S3 a bucket lifecycle rule expires it as a second safety net. Only the
transcript and metadata are kept in PostgreSQL.
"""
from __future__ import annotations

import os
import re
import tempfile
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path
from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from .config import Settings

_KEY_RE = re.compile(r"^[A-Za-z0-9/_.-]{1,200}$")


class StorageError(Exception):
    """The object store refused or failed an operation."""


class AudioNotFound(StorageError):
    """The object does not exist (already purged, or never written)."""


def validate_key(key: str) -> str:
    """Keys are generated by the API (YYYY/MM/DD/<uuid>.<ext>); reject anything else."""
    if not _KEY_RE.match(key) or ".." in key or key.startswith("/"):
        raise ValueError(f"invalid storage key: {key!r}")
    return key


class AudioStore(Protocol):
    def put(self, key: str, data: bytes, content_type: str = "application/octet-stream") -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...


class LocalAudioStore:
    def __init__(self, root: str) -> None:
        self.root = Path(root)

    def _path(self, key: str) -> Path:
        return self.root / validate_key(key)

    def put(self, key: str, data: bytes, content_type: str = "application/octet-stream") -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp, path)  # atomic: workers never read a partial file
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise AudioNotFound(key) from exc

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class S3AudioStore:
    """S3 objects under ``<prefix>/<key>``, encrypted server-side.

    ``client`` can be injected (tests, custom sessions); otherwise a boto3 client is
    built from the default credential chain.
    """

    def __init__(self, bucket: str, prefix: str = "audio", *, region: str | None = None,
                 endpoint_url: str | None = None, sse: str = "aws:kms", kms_key_id: str | None = None,
                 client=None) -> None:
        if not bucket:
            raise RuntimeError("S3_BUCKET is required when STORAGE_BACKEND=s3")
        self.bucket = bucket
        self.prefix = prefix.strip("/")
        self.sse = sse
        self.kms_key_id = kms_key_id
        if client is None:
            import boto3
            from botocore.config import Config

            client = boto3.client(
                "s3",
                region_name=region,
                endpoint_url=endpoint_url,
                config=Config(retries={"max_attempts": 5, "mode": "standard"},
                              connect_timeout=5, read_timeout=30),
            )
        self.client = client

    def _object_key(self, key: str) -> str:
        validate_key(key)
        return f"{self.prefix}/{key}" if self.prefix else key

    def put(self, key: str, data: bytes, content_type: str = "application/octet-stream") -> None:
        extra: dict[str, str] = {}
        if self.sse:
            extra["ServerSideEncryption"] = self.sse
            if self.sse == "aws:kms" and self.kms_key_id:
                extra["SSEKMSKeyId"] = self.kms_key_id
        object_key = self._object_key(key)
        with _s3_errors(key):
            self.client.put_object(Bucket=self.bucket, Key=object_key, Body=data,
                                   ContentType=content_type, **extra)

    def get(self, key: str) -> bytes:
        object_key = self._object_key(key)
        with _s3_errors(key):
            response = self.client.get_object(Bucket=self.bucket, Key=object_key)
            body = response["Body"]
            try:
                return body.read()
            finally:
                body.close()

    def delete(self, key: str) -> None:
        # Idempotent: S3 answers 204 for a key that does not exist.
        object_key = self._object_key(key)
        with _s3_errors(key):
            self.client.delete_object(Bucket=self.bucket, Key=object_key)


@contextmanager
def _s3_errors(key: str) -> Iterator[None]:
    """Map botocore errors to storage errors so callers do not depend on boto3.

    A missing object is a 404 only if the role has s3:ListBucket on the prefix;
    without it S3 answers 403 (see deploy/aws/terraform/main.tf).
    """
    from botocore.exceptions import BotoCoreError, ClientError

    try:
        yield
    except ClientError as exc:
        code = str(exc.response.get("Error", {}).get("Code", ""))
        if code in {"NoSuchKey", "404", "NotFound"}:
            raise AudioNotFound(key) from exc
        raise StorageError(f"S3 error {code or 'unknown'} on {key}") from exc
    except BotoCoreError as exc:
        raise StorageError(f"S3 unreachable ({type(exc).__name__}) on {key}") from exc


def build_store(settings: Settings) -> AudioStore:
    if settings.storage_backend == "local":
        return LocalAudioStore(settings.storage_dir)
    if settings.storage_backend == "s3":
        return S3AudioStore(
            settings.s3_bucket or "",
            settings.s3_prefix,
            region=settings.s3_region,
            endpoint_url=settings.s3_endpoint_url,
            sse=settings.s3_sse,
            kms_key_id=settings.s3_kms_key_id,
        )
    raise RuntimeError(f"unknown STORAGE_BACKEND {settings.storage_backend!r}")
